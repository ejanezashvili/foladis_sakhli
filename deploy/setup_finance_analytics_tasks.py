from datetime import datetime, time, timedelta

import pytz
from markupsafe import Markup

from odoo import fields

CTX = dict(sh_flow_internal=True, sh_no_log=True, tracking_disable=True, mail_create_nolog=True,
           mail_auto_subscribe_no_notify=True, mail_notrack=True)
Task = env['project.task'].sudo().with_context(**CTX)
Section = env['steelhouse.task.section'].sudo()

project = env['project.project'].sudo().search([('sh_is_department', '=', True), ('name', '=', DEPARTMENT)])
assert len(project) == 1, 'department board not found: %s' % DEPARTMENT
dept = project.sh_department_id
stage = project.type_ids.filtered(lambda s: s.sh_kind == 'new')[:1]
assert dept and stage, 'no HR department / no first stage on the board'

staff = env['hr.employee'].sudo().search([('department_id', '=', dept.id), ('user_id', '!=', False)])
head = staff.filtered(lambda e: (e.job_title or '').strip() == HEAD_JOB).user_id
analysts = staff.filtered(lambda e: (e.job_title or '').strip() == ANALYST_JOB).user_id.sorted('id')
root = dept
while root.parent_id:
    root = root.parent_id
directors = root.sh_all_manager_user_ids.filtered(lambda u: u.active and not u.share).sorted('id')
assert len(head) == 1 and analysts and directors, 'people not found: head %s, analysts %s, directors %s' % (
    head.mapped('name'), analysts.mapped('name'), directors.mapped('name'))
ROLE = {'დირექტორი': directors, 'ანალიტიკის განყოფილების ხელმძღვანელი': head, 'ანალიტიკოსი': analysts}
print('board:', project.name, '| first stage:', stage.name)
for role, users in ROLE.items():
    print('  %s = %s' % (role, ', '.join(users.mapped('name'))))


def end_of_day(day):
    local = pytz.timezone('Asia/Tbilisi').localize(datetime.combine(day, time(23, 59)))
    return local.astimezone(pytz.utc).replace(tzinfo=None)


def description(row, with_steps):
    parts = [Markup('<p>%s</p>') % row['result']]
    if with_steps:
        parts.append(Markup('<p>ეტაპები: %s</p>') % ' → '.join(row['steps']))
    info = 'დავალებას აძლევს: %s. მტკიცებულება: %s. ვადის გადაცილებისას ეცნობოს: %s. სიხშირე: %s%s; ჩვეულებრივ სრულდება: %s.' % (
        row['giver'], row['evidence'], row['escalate'], row['freq'],
        row['per_month'] and '; თვეში ~%s' % row['per_month'] or '', row['duration'])
    parts.append(Markup('<p>%s</p>') % info)
    if row['others']:
        parts.append(Markup('<p>სხვა დეპარტამენტების მონაწილეობა: %s.</p>') % row['others'])
    if row['note']:
        parts.append(Markup('<p>%s</p>') % row['note'])
    return Markup('').join(parts)


existing = set(Task.with_context(active_test=False).search(
    [('project_id', '=', project.id), ('parent_id', '=', False), ('state', '!=', '1_canceled'),
     '|', ('sh_repeat', '=', True), ('is_template', '=', True)]).mapped('name'))
created = Task.browse()
made = {'repeating': 0, 'steps': 0, 'templates': 0, 'subtasks': 0, 'skipped': 0}

for row in TASKS:
    name = row['name']
    doers, reviewers = ROLE[row['doer']], ROLE[row['checker']]
    steps = row['steps'][:-1] if row['steps'] and row['steps'][-1] == LAST_STEP else row['steps']
    unit = UNIT.get(row['freq'])
    kind = 'repeating / %s' % unit if unit else 'template'
    if name in existing:
        made['skipped'] += 1
        print('SKIP (already there):', name)
        continue
    print('%-17s | %s | does: %s | checks: %s | %d steps' % (
        kind, name, ', '.join(doers.mapped('name')), ', '.join(reviewers.mapped('name')), len(steps)))
    made['repeating' if unit else 'templates'] += 1
    made['steps' if unit else 'subtasks'] += len(steps)
    if MODE == 'dry':
        continue
    vals = {
        'name': name,
        'project_id': project.id,
        'stage_id': stage.id,
        'user_ids': [(6, 0, doers.ids)],
        'sh_responsible_id': doers[:1].id,
        'reviewer_ids': [(6, 0, reviewers.ids)],
        'priority': PRIORITY.get(row['priority'], '1'),
        'sh_category': 'finance',
        'evidence_required': row['evidence'] not in ('', 'არ სჭირდება'),
    }
    if not unit:
        # template: steps as sub-tasks in one stage, nobody on them (what "შაბლონად შენახვა" makes of a checklist)
        template = Task.create(dict(vals, is_template=True, description=description(row, False)))
        created |= template
        env.flush_all()
        section = Section.create({'task_id': template.id, 'name': '', 'sequence': 10})
        for n, step in enumerate(steps):
            Task.create({'name': step, 'parent_id': template.id, 'project_id': project.id, 'sequence': 10 + n,
                         'sh_section_id': section.id, 'user_ids': [(6, 0, [])],
                         'reviewer_ids': [(6, 0, reviewers.ids)], 'display_in_project': False})
        env.flush_all()
        continue
    start = fields.Date.to_date(START[unit])
    vals.update({'sh_work_start': start, 'date_deadline': end_of_day(start + timedelta(days=DAYS.get(row['duration'], 0)))})
    # a step asks for no file of its own: the evidence is attached to the main task
    step_vals = dict(vals, evidence_required=False)
    if STEP_SELF_REVIEW:
        step_vals['reviewer_ids'] = [(6, 0, doers.ids)]
    previous = Task.browse()
    for step in steps:
        previous = Task.create(dict(step_vals, name=step, depend_on_ids=[(6, 0, previous.ids)]))
        if previous.depend_on_ids:
            previous.write({'state': '04_waiting_normal'})
    created |= Task.create(dict(vals, description=description(row, True), depend_on_ids=[(6, 0, previous.ids)],
                                sh_repeat=True, sh_repeat_interval=1, sh_repeat_unit=unit, sh_repeat_start=start))
    env.flush_all()

print('TOTAL', made)
if MODE != 'dry':
    env.flush_all()
    created.invalidate_recordset()
    for task in created:
        steps = task._sh_all_previous().sorted('id')
        subs = task.with_context(active_test=False).child_ids
        print('%s | %s | %s | stage %s / %s | next %s | due %s | does %s | checks %s' % (
            task.is_template and 'TEMPLATE' or task.sh_number, task.name,
            task.sh_repeat and 'every %s %s' % (task.sh_repeat_interval, task.sh_repeat_unit) or '-',
            task.stage_id.name, task.state, task.sh_repeat_next, task.date_deadline,
            task.user_ids.mapped('name'), task.reviewer_ids.mapped('name')))
        for t in steps:
            print('      step %s | %s | %s | step=%s | does %s | checks %s' % (
                t.sh_number, t.name, t.state, t.sh_is_step, t.user_ids.mapped('name'), t.reviewer_ids.mapped('name')))
        for t in subs.sorted('sequence'):
            print('      sub  %s | template=%s | number=%s | does %s' % (t.name, t.is_template, t.sh_number, t.user_ids.mapped('name')))
